"""Lê o seletor ``/model`` do Copilot CLI e grava o cache ``~/.meister/model_catalog/copilot.json``.

Opt-in: só roda pelo comando ``meister config refresh-models copilot``. O Copilot é aberto
numa pasta temporária vazia dentro de um terminal simulado (pty); nenhum prompt é enviado,
só ``/model``, e o processo é encerrado com ESC e Ctrl-C.
"""

from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
import tempfile
import time
from dataclasses import dataclass, field
from datetime import datetime
from typing import Any, Dict, List, Optional, Tuple

from meister import osops

# Tamanho do terminal simulado (linhas, colunas), como no roteiro do seletor.
TERMINAL_ROWS = 60
TERMINAL_COLUMNS = 160

# Tempo sem saída que indica que a TUI terminou de desenhar a tela.
SETTLE_SECONDS = 1.0
# Prazo total para chegar ao seletor.
TIMEOUT_SECONDS = 60.0
# Espera depois de ESC/Ctrl-C antes de encerrar o grupo de processos à força.
EXIT_GRACE_SECONDS = 3.0

CATALOG_FILE_NAME = "copilot.json"
SOURCE_LABEL = "copilot /model (interactive TUI)"
NOTE_TEXT = (
    "Generated by meister config refresh-models copilot from the /model selector; "
    "ids are not verified (id_verified: false)."
)

_TRUST_PROMPT_MARK = "1. Yes"
_TRUST_PROMPT_WORD = re.compile(r"trust", re.IGNORECASE)
_SELECTOR_HEADER = re.compile(r"^(recent|recommended|other|unavailable) models\b", re.IGNORECASE)
_LOCAL_HEADER = re.compile(r"ollama|local", re.IGNORECASE)
_OLLAMA_ID = re.compile(r"^[\w.\-]+:[\w.\-]+(?=\s|$)")
# Linha de modelo: o tier é uma das palavras conhecidas e fica colado ao nome na tela real
# (``Claude Haiku 5.5Lightweight``); contexto e esforço vêm em seguida, com ou sem espaço.
_ROW = re.compile(
    r"^(?P<name>.*?\S)\s*(?P<marks>(?:✓|\(default\)|\s)*)"
    r"(?P<tier>Lightweight|Versatile|Powerful)\s*"
    r"(?P<context>\d+(?:\.\d+)?[KkMm]|—|-)\s*"
    r"(?P<effort>Low|Medium|High|—|-)$"
)
# Modelo indisponível: só o id seguido de ``— —``.
_UNAVAILABLE_ROW = re.compile(r"^(?P<name>.*?\S)\s*—\s*—$")
_ROW_EDGES = " \t│|❯>›*•▸▶"
# Moldura da TUI (barra de rolagem, backspace de sobrescrita) que não faz parte do texto.
_FRAME = re.compile(r"[\x08┃│]")

# Sequências ANSI/OSC/CSI; o avanço do cursor (CSI n C) vira espaço para não colar palavras.
_CURSOR_FORWARD = re.compile(r"\x1b\[(\d*)C")
_ANSI = re.compile(r"\x1b\[[0-?]*[ -/]*[@-~]|\x1b\][^\x07\x1b]*(?:\x07|\x1b\\)|\x1b[@-Z\\-_]")

# Consultas que a TUI faz ao abrir: cores (OSC 4/10/11), esquema de cores (996) e modos (DECRQM).
_QUERY = re.compile(
    rb"\x1b\]4;(?P<palette>\d+);\?(?:\x07|\x1b\\)"
    rb"|\x1b\](?P<osc>10|11);\?(?:\x07|\x1b\\)"
    rb"|\x1b\[\?996n"
    rb"|\x1b\[\?(?P<mode>\d+)\$p"
)
# Uma consulta incompleta cabe em poucos bytes; guarda só o final do buffer entre leituras.
_QUERY_TAIL_BYTES = 64


class CopilotModelsError(Exception):
    """Falha que o comando mostra ao usuário: ``key`` é uma mensagem de ``cli.config.refresh_models.*``."""

    def __init__(self, key: str, **fields: Any) -> None:
        super().__init__(key)
        self.key = key
        self.fields = fields


@dataclass
class ParsedSelector:
    """Conteúdo do seletor ``/model`` já organizado em grupos."""

    models: List[Dict[str, Any]] = field(default_factory=list)
    unavailable: List[str] = field(default_factory=list)
    local_ollama: List[str] = field(default_factory=list)


def catalog_path() -> str:
    """Caminho do cache do Copilot; respeita ``HOME``."""
    return os.path.join(os.path.expanduser("~"), ".meister", "model_catalog", CATALOG_FILE_NAME)


def strip_ansi(text: str) -> str:
    """Tira as sequências de controle da saída da TUI e devolve só o texto visível."""
    text = _CURSOR_FORWARD.sub(lambda match: " " * max(int(match.group(1) or 1), 1), text)
    return _ANSI.sub("", text).replace("\r", "\n")


def model_id_from_name(name: str) -> str:
    """Id provisório: minúsculas e espaços viram hífens (regra observada no ``/model``)."""
    return "-".join(name.lower().split())


def _reply_for(match: "re.Match[bytes]") -> bytes:
    if match.group("palette") is not None:
        return b"\x1b]4;" + match.group("palette") + b";rgb:8080/8080/8080\x1b\\"
    if match.group("osc") == b"10":
        return b"\x1b]10;rgb:ffff/ffff/ffff\x1b\\"
    if match.group("osc") == b"11":
        return b"\x1b]11;rgb:0000/0000/0000\x1b\\"
    if match.group("mode") is not None:
        return b"\x1b[?" + match.group("mode") + b";2$y"
    # CSI ? 996 n: esquema de cores; 1 = escuro
    return b"\x1b[?997;1n"


def answer_terminal_queries(buffer: bytes) -> Tuple[bytes, bytes]:
    """Responde às consultas completas de ``buffer``; devolve ``(respostas, resto)``.

    ``resto`` é o final do buffer que pode ser o começo de uma consulta ainda incompleta.
    """
    replies = []
    end = 0
    for match in _QUERY.finditer(buffer):
        replies.append(_reply_for(match))
        end = match.end()
    return b"".join(replies), buffer[end:][-_QUERY_TAIL_BYTES:]


def _clean(line: str) -> str:
    """Tira a moldura e as bordas de uma linha do seletor."""
    return _FRAME.sub(" ", line).strip(_ROW_EDGES)


def _row_fields(line: str) -> Optional[Dict[str, Any]]:
    """Lê ``Nome [✓] [(default)] Tier Contexto Esforço``; devolve None se a linha não for um modelo."""
    match = _ROW.match(_clean(line))
    if match is None:
        return None
    name = " ".join(match.group("name").split())
    if not re.search(r"[A-Za-z]", name):
        return None
    # O marcador ✓ e (default) ficam entre o nome e o tier.
    marks = match.group("marks")
    return {
        "name": name,
        "selected": "✓" in marks,
        "default": "(default)" in marks,
        "tier": match.group("tier"),
        "context": _dash_to_none(match.group("context")),
        "reasoning": _dash_to_none(match.group("effort")),
    }


def _dash_to_none(value: str) -> Optional[str]:
    return None if value in ("—", "-") else value


def parse_selector(text: str) -> ParsedSelector:
    """Lê o seletor a partir do texto já sem ANSI; grupos desconhecidos e linhas soltas são ignorados."""
    parsed = ParsedSelector()
    seen: set = set()
    group: Optional[str] = None
    for raw in text.split("\n"):
        line = _clean(raw)
        if not line:
            continue
        header = _SELECTOR_HEADER.match(line)
        if header is not None:
            group = header.group(1).lower()
            continue
        fields = _row_fields(line)
        if fields is None and _LOCAL_HEADER.search(line) and len(line) <= 80:
            group = "local"
            continue
        if group == "local":
            ollama = _OLLAMA_ID.match(line)
            if ollama is not None and ollama.group(0) not in parsed.local_ollama:
                parsed.local_ollama.append(ollama.group(0))
            continue
        if group is None:
            continue
        if group == "unavailable":
            # Tela real: só ``id — —``; uma linha de modelo completa também conta.
            unavailable = _UNAVAILABLE_ROW.match(line)
            name = unavailable.group("name") if unavailable is not None else (fields or {}).get("name")
            if name is not None:
                model_id = model_id_from_name(name)
                if model_id not in parsed.unavailable:
                    parsed.unavailable.append(model_id)
            continue
        if fields is None:
            continue
        model_id = model_id_from_name(fields["name"])
        if model_id in seen:
            continue
        seen.add(model_id)
        parsed.models.append(
            {
                "name": fields["name"],
                "group": group,
                "tier": fields["tier"],
                "context": fields["context"],
                "reasoning": fields["reasoning"],
                "selected": fields["selected"],
                "default": fields["default"],
                "id": model_id,
                "id_verified": False,
            }
        )
    return parsed


def _has_selector(text: str) -> bool:
    return any(_SELECTOR_HEADER.match(_clean(line)) for line in text.split("\n"))


def _has_trust_prompt(text: str) -> bool:
    return _TRUST_PROMPT_MARK in text and _TRUST_PROMPT_WORD.search(text) is not None


def _open_pty(rows: int, columns: int) -> Tuple[int, int]:
    """Abre um terminal simulado ``(mestre, escravo)`` com o tamanho de janela pedido."""
    import pty

    master, slave = pty.openpty()
    try:
        # stty ajusta o tamanho do escravo sem importar fcntl (proibido fora de meister/osops/).
        # Procurado no caminho padrão do sistema: o PATH do usuário não precisa tê-lo.
        stty = shutil.which("stty", path=os.defpath) or "stty"
        subprocess.run(
            [stty, "rows", str(rows), "columns", str(columns)],
            stdin=slave,
            check=True,
            timeout=5,
        )
    except BaseException:
        os.close(master)
        os.close(slave)
        raise
    return master, slave


def _open_terminal(executable: str, cwd: str) -> Tuple[int, subprocess.Popen]:
    """Abre o Copilot num pty de 60x160; devolve (fd mestre, processo)."""
    master, slave = _open_pty(TERMINAL_ROWS, TERMINAL_COLUMNS)
    try:
        env = dict(os.environ, TERM="xterm-256color")
        process = subprocess.Popen(
            [executable],
            stdin=slave,
            stdout=slave,
            stderr=slave,
            cwd=cwd,
            env=env,
            close_fds=True,
            **osops.popen_session_kwargs(),
        )
    except BaseException:
        os.close(master)
        raise
    finally:
        os.close(slave)
    return master, process


def _read_chunk(master: int) -> Optional[bytes]:
    """Lê o que o terminal mandou (None = nada nesta janela, b"" = fim do terminal)."""
    import select

    ready, _, _ = select.select([master], [], [], 0.1)
    if not ready:
        return None
    try:
        return os.read(master, 65536)
    except OSError:
        return b""


def _drive_selector(master: int, process: subprocess.Popen) -> str:
    """Conduz a TUI até o seletor aparecer; devolve a saída bruta acumulada."""
    transcript = b""
    queries = b""
    last_output = time.monotonic()
    deadline = last_output + TIMEOUT_SECONDS
    trust_answered = False
    model_sent = False
    trust_start = 0
    model_start = 0

    while time.monotonic() < deadline:
        chunk = _read_chunk(master)
        now = time.monotonic()
        if chunk == b"":
            raise CopilotModelsError("cli.config.refresh_models.exited")
        if chunk:
            transcript += chunk
            last_output = now
            replies, queries = answer_terminal_queries(queries + chunk)
            if replies:
                os.write(master, replies)
            continue
        if not transcript or now - last_output < SETTLE_SECONDS:
            continue
        if process.poll() is not None:
            raise CopilotModelsError("cli.config.refresh_models.exited")

        screen = strip_ansi(transcript.decode("utf-8", errors="replace"))
        if not trust_answered and _has_trust_prompt(screen[trust_start:]):
            os.write(master, b"1\r")
            trust_answered = True
            last_output = time.monotonic()
            trust_start = len(screen)
            continue
        if not model_sent and not _has_trust_prompt(screen[trust_start:]):
            os.write(master, b"/model")
            time.sleep(0.3)
            os.write(master, b"\r")
            model_sent = True
            model_start = len(screen)
            last_output = time.monotonic()
            continue
        if model_sent and _has_selector(screen[model_start:]):
            return screen

    raise CopilotModelsError("cli.config.refresh_models.timeout", seconds=int(TIMEOUT_SECONDS))


def _close_terminal(master: int, process: subprocess.Popen) -> None:
    """ESC, Ctrl-C e, se o processo não sair, encerra o grupo; nunca deixa o filho para trás."""
    if process.poll() is None:
        for keys in (b"\x1b", b"\x03"):
            try:
                os.write(master, keys)
            except OSError:
                break
            time.sleep(0.3)
        exit_deadline = time.monotonic() + EXIT_GRACE_SECONDS
        while process.poll() is None and time.monotonic() < exit_deadline:
            _read_chunk(master)
    if process.poll() is None:
        osops.terminate_tree(process.pid, grace=1.0, wait=_waiter(process))
    try:
        process.wait(timeout=5)
    except subprocess.TimeoutExpired:
        pass


def _waiter(process: subprocess.Popen):
    def wait(timeout: float) -> bool:
        try:
            process.wait(timeout=timeout)
            return True
        except subprocess.TimeoutExpired:
            return False

    return wait


def read_copilot_selector() -> str:
    """Abre o ``copilot`` numa pasta temporária vazia e devolve o texto do seletor ``/model``."""
    if sys.platform == "win32":
        raise CopilotModelsError("cli.config.refresh_models.unsupported_platform")
    executable = shutil.which("copilot")
    if executable is None:
        raise CopilotModelsError("cli.config.refresh_models.no_copilot")

    with tempfile.TemporaryDirectory(prefix="meister-copilot-") as workdir:
        master, process = _open_terminal(executable, workdir)
        try:
            return _drive_selector(master, process)
        finally:
            try:
                _close_terminal(master, process)
            finally:
                os.close(master)


def write_catalog(parsed: ParsedSelector, path: str, captured_at: str) -> None:
    """Grava o cache de forma atômica; o arquivo anterior vira ``<path>.bak``."""
    directory = os.path.dirname(path)
    os.makedirs(directory, exist_ok=True)
    document = {
        "source": SOURCE_LABEL,
        "captured_at": captured_at,
        "note": NOTE_TEXT,
        "models": parsed.models,
        "unavailable": parsed.unavailable,
        "local_ollama": parsed.local_ollama,
    }
    handle, temp_path = tempfile.mkstemp(prefix=".copilot-", suffix=".tmp", dir=directory)
    backup_temp = temp_path + ".bak"
    try:
        with os.fdopen(handle, "w", encoding="utf-8") as stream:
            json.dump(document, stream, ensure_ascii=False, indent=2)
            stream.write("\n")
        if os.path.exists(path):
            shutil.copyfile(path, backup_temp)
            os.replace(backup_temp, path + ".bak")
        os.replace(temp_path, path)
    finally:
        for leftover in (temp_path, backup_temp):
            if os.path.exists(leftover):
                os.remove(leftover)


def refresh_copilot_catalog() -> Tuple[int, str]:
    """Lê o seletor e atualiza o cache; devolve ``(quantidade de modelos, caminho)``.

    Sem nenhum modelo no seletor, o arquivo anterior fica intacto e a falha é levantada.
    """
    path = catalog_path()
    parsed = parse_selector(read_copilot_selector())
    if not parsed.models:
        raise CopilotModelsError("cli.config.refresh_models.no_models", path=path)
    captured_at = datetime.now().astimezone().isoformat(timespec="seconds")
    write_catalog(parsed, path, captured_at)
    return len(parsed.models), path
