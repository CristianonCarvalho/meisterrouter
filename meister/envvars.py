"""Environment variables that mark a process as a MeisterRouter worker.

``MEISTER_WORKER`` is the current name; ``MEISTER_IN_PANE`` is kept so that
hooks generated by older installations keep recognising workers.
"""

from __future__ import annotations

import os
from collections.abc import Mapping

WORKER_ENV_NAMES: tuple[str, ...] = ("MEISTER_WORKER", "MEISTER_IN_PANE")


def worker_env_assignments() -> dict[str, str]:
    """Return the variables a worker launcher must set, each to ``"1"``."""
    return {name: "1" for name in WORKER_ENV_NAMES}


def is_worker_env(env: Mapping[str, str] | None = None) -> bool:
    """Return True if any worker variable is ``"1"`` in ``env``.

    When ``env`` is omitted, ``os.environ`` is consulted.
    """
    source: Mapping[str, str] = os.environ if env is None else env
    return any(source.get(name) == "1" for name in WORKER_ENV_NAMES)
